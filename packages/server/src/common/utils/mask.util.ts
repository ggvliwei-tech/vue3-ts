/**
 * 敏感信息脱敏工具
 *
 * 用在**审计日志**这类长期留存、可导出、且被多个管理员读取的地方。
 */

/**
 * 手机号脱敏：保留前 3 位与后 4 位，中间用 `*` 填充（`138****8000`）。
 *
 * 为什么审计日志里不能存完整号码：
 * 审计表是**长期留存**（AUDIT_RETENTION_DAYS 天）且**可导出 CSV** 的。
 * 把完整手机号写进去，等于把它复制到了另一处不受用户密码保护的地方 ——
 * 用户改绑手机号、甚至注销账号之后，原号码仍能从审计表里被翻出来，
 * 而且持有 `admin:audit` 权限的人都能看到、能一次性导走。
 *
 * 脱敏不影响审计的用途：审计要回答的是「谁、在什么时候、对被谁做了什么」，
 * 掩码后的号码足以在追查时定位到具体用户（配合 userId 字段即可唯一确定），
 * 完整号码对这个问题没有增量信息。
 *
 * 非 11 位数字的输入原样返回：调用方的字段虽然都经过 `^1[3-9]\d{9}$` 校验，
 * 但这个函数是通用的 —— 与其"猜"着截断（会把审计线索一起抹掉），
 * 不如老实地原样透出，让异常输入暴露出来。
 */
export function maskPhone(phone: string): string {
  const value = String(phone ?? '')
  if (!/^1[3-9]\d{9}$/.test(value)) return value
  return `${value.slice(0, 3)}****${value.slice(7)}`
}
